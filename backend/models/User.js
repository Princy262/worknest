import mongoose from 'mongoose';
import bcrypt from 'bcryptjs';
import { ROLES, EMPLOYMENT_STATUS } from '../utils/constants.js';

const userSchema = new mongoose.Schema(
  {
    // ----- Identity (set by the creator) -----
    name: {
      type: String,
      required: [true, 'Name is required'],
      trim: true,
    },
    email: {
      type: String,
      required: [true, 'Email is required'],
      unique: true,
      lowercase: true,
      trim: true,
    },
    employeeId: {
      type: String,
      trim: true,
      required: function () {
        return this.role !== ROLES.PLATFORM_OWNER;
      },
    },
    username: {
      type: String,
      required: true,
      trim: true, // generated by the server, e.g. Rahul123
    },

    // ----- Security -----
    password: {
      type: String,
      required: [true, 'Password is required'],
      minlength: 8,
      select: false, // never returned in queries unless asked for
    },
    mustChangePassword: {
      type: Boolean,
      default: true,
    },

    // ----- Role and position -----
    role: {
      type: String,
      enum: Object.values(ROLES),
      default: ROLES.EMPLOYEE,
    },
    designation: {
      type: String,
      trim: true,
    },
    employmentStatus: {
      type: String,
      enum: Object.values(EMPLOYMENT_STATUS),
      default: EMPLOYMENT_STATUS.ACTIVE,
    },

    // ----- Contact info (the employee can edit this later) -----
    contact: {
      phone: { type: String, trim: true },
      address: { type: String, trim: true },
      emergencyContact: { type: String, trim: true },
    },

    // ----- Position in the hierarchy -----
    company: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'Company',
      required: function () {
        return this.role !== ROLES.PLATFORM_OWNER;
      },
    },
    department: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'Department',
    },
    team: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'Team',
    },
    reportingManager: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'User',
    },
  },
  { timestamps: true }
);

// Employee IDs are unique inside one company (two companies can both have employee 123).
userSchema.index({ company: 1, employeeId: 1 }, { unique: true, sparse: true });

// Usernames are unique everywhere, ignoring upper/lower case (Rahul123 = rahul123).
userSchema.index(
  { username: 1 },
  { unique: true, collation: { locale: 'en', strength: 2 } }
);

// Hash the password automatically before saving, but only when it changed.
userSchema.pre('save', async function () {
  if (!this.isModified('password')) return;
  this.password = await bcrypt.hash(this.password, 10);
});

// Used at login: compares a typed password with the stored hash.
userSchema.methods.matchPassword = async function (enteredPassword) {
  return bcrypt.compare(enteredPassword, this.password);
};

// Make sure the password hash never appears when a user is sent as JSON.
userSchema.set('toJSON', {
  transform: (doc, ret) => {
    delete ret.password;
    return ret;
  },
});

const User = mongoose.model('User', userSchema);

export default User;